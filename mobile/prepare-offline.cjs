const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const root = path.join(__dirname,'dist');
const walk = (dir) => fs.readdirSync(dir,{withFileTypes:true}).flatMap(e=>e.isDirectory()?walk(path.join(dir,e.name)):[path.join(dir,e.name)]);
const files=walk(root).filter(f=>path.basename(f)!=='sw.js').sort();
const hash=crypto.createHash('sha256');
files.forEach(f=>hash.update(path.relative(root,f)).update(fs.readFileSync(f)));
const cache='yunxin-mobile-'+hash.digest('hex').slice(0,12);
fs.writeFileSync(path.join(root,'sw.js'),`/* Generated by prepare-offline.cjs. No user data or external responses are cached. */
const CACHE = ${JSON.stringify(cache)};
const FILES = ${JSON.stringify(files.map(f=>'./'+path.relative(root,f).replaceAll(path.sep,'/')))};
const BASE = new URL('./',self.location.href);
const PATHS = new Set(FILES.map(f=>new URL(f,BASE).pathname));
self.addEventListener('install',event=>event.waitUntil(caches.open(CACHE).then(cache=>cache.addAll(FILES))));
self.addEventListener('activate',event=>event.waitUntil((async()=>{
  const keys=await caches.keys();
  await Promise.all(keys.filter(k=>k.startsWith('yunxin-mobile-')&&k!==CACHE).map(k=>caches.delete(k)));
  await self.clients.claim();
})()));
self.addEventListener('fetch',event=>{
  const url=new URL(event.request.url);
  if(event.request.method!=='GET'||url.origin!==BASE.origin)return;
  const isAppDocument=event.request.mode==='navigate'&&(url.pathname===BASE.pathname||url.pathname===new URL('index.html',BASE).pathname);
  if(!isAppDocument&&!PATHS.has(url.pathname))return;
  event.respondWith((async()=>{
    const cache=await caches.open(CACHE);
    const hit=await cache.match(isAppDocument?new URL('index.html',BASE).href:event.request,{ignoreSearch:true});
    return hit||fetch(event.request);
  })());
});
`);
console.log(JSON.stringify({cache,files:files.length}));
